#!/usr/bin/env node
/* parseSpeech POC emitter
 *
 * 从 `3d/preview/data/lines.json` 读取 2.5D 导出的词表/正则，生成一个**独立**的
 * GDScript 解析器 `3d/preview/poc/generated_parse_speech.gd`。
 *
 * 边界（POC，不是生产 codegen）：
 *   · 词表 / 席位表 / 意图正则是自动提取的；
 *   · 控制流仍是固定的算法模板（parseSpeech 的槽位抽取步骤）；
 *   · 真正的通用 JS→GDScript 需要 IR，见 3d/reports/portability-audit.md。
 *
 * 用法：node 3d/tools/poc-gen-parse-speech.cjs
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const LINES = path.join(ROOT, '3d/preview/data/lines.json');
const OUT = path.join(ROOT, '3d/preview/poc/generated_parse_speech.gd');

const data = JSON.parse(fs.readFileSync(LINES, 'utf8'));
const patterns = data.speech_patterns || {};
const claimKinds = patterns.claim_kinds || [];
if (!Array.isArray(data.room_words) || !data.room_words.length) throw new Error('lines.json 缺 room_words');
if (!data.cn_seat || !Object.keys(data.cn_seat).length) throw new Error('lines.json 缺 cn_seat');
if (!claimKinds.length) throw new Error('lines.json 缺 speech_patterns.claim_kinds');

const lit = (v) => JSON.stringify(v, null, 2).replace(/\n/g, '\n');

const gd = `# AUTO-GENERATED by 3d/tools/poc-gen-parse-speech.cjs — 请勿手改。
# 源：3d/preview/data/lines.json（由 js/t2/decision.js 导出）
# POC 边界：词表/正则自动生成；控制流是 parseSpeech 的固定模板。
extends RefCounted

const ROOM_WORDS = ${lit(data.room_words)}

const CN_SEAT = ${lit(data.cn_seat)}

const PATTERNS = ${lit({
  support: patterns.support,
  neg_vote: patterns.neg_vote,
  neg_acc: patterns.neg_acc,
  neg_see: patterns.neg_see,
  saw: patterns.saw,
  accuse: patterns.accuse,
  vote: patterns.vote,
  deny: patterns.deny,
  where: patterns.where,
  when_recent: patterns.when_recent,
  when_night: patterns.when_night,
})}

const CLAIM_KINDS = ${lit(claimKinds)}


func parse_speech(text: String, sim) -> Dictionary:
\tvar s := text
\tvar out := {
\t\t"raw": s.substr(0, 80), "rooms": [], "people": [], "accuse": -1, "vote": -1,
\t\t"deny": false, "where": "", "when": "", "claim": {}, "support": -1,
\t}
\tfor pair: Array in ROOM_WORDS:
\t\tif s.find(String(pair[0])) >= 0 and not (out["rooms"] as Array).has(String(pair[1])):
\t\t\t(out["rooms"] as Array).append(String(pair[1]))
\tvar spans: Array = []
\tvar at: Dictionary = {}
\tvar names: Array = []
\tfor a: Dictionary in sim.agents:
\t\tif int(a.get("i", -1)) == int(sim.me_idx):
\t\t\tcontinue
\t\tnames.append([String(a.get("name", "")), int(a.get("i", -1))])
\tnames.sort_custom(func(x, y):
\t\tvar lx := String(x[0]).length()
\t\tvar ly := String(y[0]).length()
\t\tif lx != ly:
\t\t\treturn lx > ly
\t\treturn int(x[1]) < int(y[1]))
\tfor pair: Array in names:
\t\tvar nm := String(pair[0])
\t\tvar idx := int(pair[1])
\t\tvar from := 0
\t\tvar pos := -1
\t\twhile true:
\t\t\tpos = s.find(nm, from)
\t\t\tif pos < 0:
\t\t\t\tbreak
\t\t\tif _free_span(spans, pos, nm.length()):
\t\t\t\tbreak
\t\t\tfrom = pos + 1
\t\tif pos >= 0:
\t\t\t_note_at(at, idx, pos)
\t\t\tspans.append([pos, pos + nm.length()])
\t\tvar seat := "%02d" % (idx + 1)
\t\tvar sp := s.find(seat)
\t\tif sp >= 0 and _free_span(spans, sp, seat.length()):
\t\t\t_note_at(at, idx, sp)
\t\t\tspans.append([sp, sp + seat.length()])
\tvar re_num := RegEx.new()
\tre_num.compile("(?:第\\\\s*)?0?([1-9]|1[0-5])\\\\s*(?:号|席)")
\tfor m: RegExMatch in re_num.search_all(s):
\t\tvar idx2 := int(m.get_string(1)) - 1
\t\tif idx2 >= 0 and idx2 != int(sim.me_idx) and idx2 < sim.agents.size() \\
\t\t\t\tand _free_span(spans, m.get_start(), 1):
\t\t\t_note_at(at, idx2, m.get_start())
\tvar re_cn := RegEx.new()
\tre_cn.compile("([一二三四五六七八九十]{1,3})\\\\s*(?:号|席)")
\tfor m2: RegExMatch in re_cn.search_all(s):
\t\tvar idx3 := int(CN_SEAT.get(m2.get_string(1), 0)) - 1
\t\tif idx3 >= 0 and idx3 != int(sim.me_idx) and idx3 < sim.agents.size() \\
\t\t\t\tand _free_span(spans, m2.get_start(), 1):
\t\t\t_note_at(at, idx3, m2.get_start())
\tvar keys: Array = at.keys()
\tkeys.sort_custom(func(x, y): return int(at[x]) < int(at[y]))
\tout["people"] = keys
\tvar first := int(keys[0]) if not keys.is_empty() else -1
\tvar has_people := first >= 0
\tvar support := has_people and _has("support", s)
\tvar neg_vote := _has("neg_vote", s)
\tvar neg_acc := _has("neg_acc", s)
\tvar neg_see := _has("neg_see", s)
\tif support:
\t\tout["support"] = first
\tvar claim_kind := ""
\tif not support:
\t\tfor c: Dictionary in CLAIM_KINDS:
\t\t\tvar re := RegEx.new()
\t\t\tre.compile(String(c.get("pattern", "")))
\t\t\tif re.search(s) != null:
\t\t\t\tclaim_kind = String(c.get("kind", ""))
\t\t\t\tbreak
\tif claim_kind != "" and _has("saw", s) and not neg_see and has_people and not support:
\t\tvar rooms: Array = out["rooms"] as Array
\t\tout["claim"] = {"target": first, "kind": claim_kind,
\t\t\t"room": String(rooms[0]) if not rooms.is_empty() else ""}
\tif not support and (out["claim"] as Dictionary).is_empty():
\t\tif has_people and _has("accuse", s) and not neg_acc:
\t\t\tout["accuse"] = first
\t\tif has_people and _has("vote", s) and not neg_vote:
\t\t\tout["vote"] = first
\tif _has("deny", s):
\t\tout["deny"] = true
\tvar rooms2: Array = out["rooms"] as Array
\tif not rooms2.is_empty() and _has("where", s):
\t\tout["where"] = String(rooms2[0])
\tif _has("when_recent", s):
\t\tout["when"] = "recent"
\telif _has("when_night", s):
\t\tout["when"] = "night"
\treturn out


func _has(key: String, text: String) -> bool:
\tif not PATTERNS.has(key):
\t\treturn false
\tvar re := RegEx.new()
\tre.compile(String(PATTERNS[key]))
\treturn re.search(text) != null


func _free_span(spans: Array, start: int, len_: int) -> bool:
\tfor sp: Array in spans:
\t\tif start < int(sp[1]) and start + len_ > int(sp[0]):
\t\t\treturn false
\treturn true


func _note_at(at: Dictionary, idx: int, pos: int) -> void:
\tif not at.has(idx) or pos < int(at[idx]):
\t\tat[idx] = pos
`;

fs.writeFileSync(OUT, gd, 'utf8');
console.log(`POC EMIT ${path.relative(ROOT, OUT)}（${gd.split('\n').length} 行）`);
