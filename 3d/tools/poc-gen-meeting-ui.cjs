#!/usr/bin/env node
/* 会议面板 UI spec → Godot Control POC 生成器
 *
 * 只消费 `3d/spec/ui/meeting-panel.spec.json`，生成
 * `3d/preview/poc/generated_meeting_panel.gd`：
 *   · 17 个元素 → 对应 Control 节点；
 *   · 11 个模板 → 按钮；
 *   · 3 个状态 → apply_state() 可见性；
 * 不生成业务 handler，不替换运行时 main.gd。
 *
 * 用法：node 3d/tools/poc-gen-meeting-ui.cjs
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const SPEC = path.join(ROOT, '3d/spec/ui/meeting-panel.spec.json');
const OUT = path.join(ROOT, '3d/preview/poc/generated_meeting_panel.gd');

const spec = JSON.parse(fs.readFileSync(SPEC, 'utf8'));
const byId = new Map(spec.elements.map(e => [e.id, e]));
const children = new Set();
for (const e of spec.elements) for (const r of e.requires || []) children.add(r);

const q = (s) => JSON.stringify(String(s));
const arr = (a) => JSON.stringify(a);
const states = Object.fromEntries((spec.states || []).map(s => [s.id, { show: s.show || [], hide: s.hide || [] }]));

const lines = [];
lines.push('# AUTO-GENERATED by 3d/tools/poc-gen-meeting-ui.cjs — 请勿手改。');
lines.push('# 源：3d/spec/ui/meeting-panel.spec.json');
lines.push('# POC 边界：只生成结构 / 状态可见性，不生成业务 handler，不替换运行时 UI。');
lines.push('extends RefCounted');
lines.push('');
lines.push(`const SPEC_ID = ${q(spec.id)}`);
lines.push(`const ELEMENT_COUNT = ${spec.elements.length}`);
lines.push(`const TEMPLATE_COUNT = ${spec.templates.length}`);
lines.push(`const STATES = ${JSON.stringify(states, null, 2)}`);
lines.push('');
lines.push('var _nodes: Dictionary = {}');
lines.push('');
lines.push('func build() -> Control:');
lines.push('\tvar root := PanelContainer.new()');
lines.push('\troot.name = "MeetingPanelPOC"');
lines.push('\tvar body := HBoxContainer.new()');
lines.push('\troot.add_child(body)');
for (const r of spec.regions) {
  lines.push(`\tvar col_${r.id} := VBoxContainer.new()`);
  lines.push(`\tcol_${r.id}.name = ${q('col_' + r.id)}`);
  lines.push(`\tbody.add_child(col_${r.id})`);
}
lines.push('\t# 标题 / 信息行放中栏，和 2.5D 的三栏信息结构对齐。');
for (const r of spec.regions) {
  lines.push(`\t_build_region(col_${r.id}, ${q(r.id)})`);
}
lines.push('\treturn root');
lines.push('');
lines.push('func node(id: String) -> Control:');
lines.push('\treturn _nodes.get(id, null)');
lines.push('');
lines.push('func apply_state(state_id: String) -> void:');
lines.push('\tvar st: Dictionary = STATES.get(state_id, {})');
lines.push('\tvar show: Array = st.get("show", [])');
lines.push('\tvar hide: Array = st.get("hide", [])');
lines.push('\tfor id: String in _nodes.keys():');
lines.push('\t\tvar n: Control = _nodes[id]');
lines.push('\t\tif show.has(id):');
lines.push('\t\t\tn.visible = true');
lines.push('\t\telif hide.has(id):');
lines.push('\t\t\tn.visible = false');
lines.push('');
lines.push('func _reg(id: String, n: Control) -> Control:');
lines.push('\tn.set_meta("spec_id", id)');
lines.push('\t_nodes[id] = n');
lines.push('\treturn n');
lines.push('');

function emitElement(el, indent, parentExpr = 'parent') {
  const t = '\t'.repeat(indent);
  const par = parentExpr;
  const id = q(el.id);
  switch (el.role) {
    case 'title':
    case 'text':
    case 'status':
    case 'result':
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_label(${par}, ${id}, ${q(el.label || '')})`);
      break;
    case 'button':
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_button(${par}, ${id}, ${q(el.label || '')})`);
      break;
    case 'input':
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_input(${par}, ${id}, ${q(el.placeholder || '')})`);
      break;
    case 'select': {
      let opts = [];
      if (Array.isArray(el.options)) opts = el.options.map(o => o.label);
      else if (el.options === 'alive_agents') opts = ['— 选择对象 —'];
      else if (el.options === 'rooms') opts = ['不指定舱室', '走廊'];
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_select(${par}, ${id}, ${arr(opts)})`);
      break;
    }
    case 'feed':
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_feed(${par}, ${id})`);
      break;
    case 'list':
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_group(${par}, ${id})`);
      break;
    case 'info_rows': {
      const rows = (el.fields || []).map(f => [f, '—']);
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_rows(${par}, ${id}, ${JSON.stringify(rows)})`);
      break;
    }
    case 'group':
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_group(${par}, ${id})`);
      for (const req of el.requires || []) {
        const child = byId.get(req);
        if (!child) continue;
        if (child.role === 'button_group') {
          lines.push(`${t}var n_${req.replace(/-/g, '_')} := _mk_grid(n_${el.id.replace(/-/g, '_')}, ${q(req)}, 4)`);
          for (const tp of spec.templates) {
            lines.push(`${t}_mk_tpl_button(n_${req.replace(/-/g, '_')}, ${q(tp.key)}, ${q(tp.label)})`);
          }
        } else {
          emitElement(child, indent, 'n_' + el.id.replace(/-/g, '_'));
        }
      }
      break;
    case 'button_group':
      // 由 group 分支负责；独立出现时也生成 grid
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_grid(${par}, ${id}, 4)`);
      for (const tp of spec.templates) {
        lines.push(`${t}_mk_tpl_button(n_${el.id.replace(/-/g, '_')}, ${q(tp.key)}, ${q(tp.label)})`);
      }
      break;
    default:
      lines.push(`${t}var n_${el.id.replace(/-/g, '_')} := _mk_group(${par}, ${id})`);
  }
}

lines.push('func _build_region(parent: VBoxContainer, region_id: String) -> void:');
lines.push('\tfor el: Dictionary in _elements_in(region_id):');
lines.push('\t\tif bool(el.get("_child", false)):');
lines.push('\t\t\tcontinue');
lines.push('\t\tmatch String(el.get("role", "")):');
for (const role of ['title', 'text', 'status', 'result', 'button', 'input', 'select', 'feed', 'list', 'info_rows', 'group', 'button_group']) {
  lines.push(`\t\t\t${q(role)}:`);
  lines.push(`\t\t\t\tpass`);
}
lines.push('\t# 具体节点由生成器在 _build_region 末尾展开（见下）。');
lines.push('');
lines.push('func _elements_in(region_id: String) -> Array:');
lines.push('\treturn []');
lines.push('');

/* 改为直接生成每个区域的显式构建函数，避免生成器再写一个解释器。 */
const byRegion = new Map(spec.regions.map(r => [r.id, []]));
for (const el of spec.elements) {
  if (!children.has(el.id)) byRegion.get(el.region).push(el);
}
// 重新生成 build 区域调用为显式函数
const buildStart = lines.findIndex(l => l.startsWith('\t# 标题 / 信息行'));
lines.splice(buildStart, lines.length - buildStart);
for (const r of spec.regions) {
  lines.push(`\t_build_${r.id}(col_${r.id})`);
}
lines.push('\treturn root');
lines.push('');
lines.push('func node(id: String) -> Control:');
lines.push('\treturn _nodes.get(id, null)');
lines.push('');
lines.push('func apply_state(state_id: String) -> void:');
lines.push('\tvar st: Dictionary = STATES.get(state_id, {})');
lines.push('\tvar show: Array = st.get("show", [])');
lines.push('\tvar hide: Array = st.get("hide", [])');
lines.push('\tfor id: String in _nodes.keys():');
lines.push('\t\tvar n: Control = _nodes[id]');
lines.push('\t\tif show.has(id):');
lines.push('\t\t\tn.visible = true');
lines.push('\t\telif hide.has(id):');
lines.push('\t\t\tn.visible = false');
lines.push('');
lines.push('func _reg(id: String, n: Control) -> Control:');
lines.push('\tn.set_meta("spec_id", id)');
lines.push('\t_nodes[id] = n');
lines.push('\treturn n');
lines.push('');

for (const r of spec.regions) {
  lines.push(`func _build_${r.id}(parent: VBoxContainer) -> void:`);
  const els = byRegion.get(r.id);
  if (!els.length) {
    lines.push('\tpass');
  } else {
    for (const el of els) emitElement(el, 1);
  }
  lines.push('');
}

lines.push('func _mk_label(parent: Control, id: String, text: String) -> Label:');
lines.push('\tvar n := Label.new()');
lines.push('\tn.text = text');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as Label');
lines.push('');
lines.push('func _mk_button(parent: Control, id: String, text: String) -> Button:');
lines.push('\tvar n := Button.new()');
lines.push('\tn.text = text');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as Button');
lines.push('');
lines.push('func _mk_input(parent: Control, id: String, placeholder: String) -> LineEdit:');
lines.push('\tvar n := LineEdit.new()');
lines.push('\tn.placeholder_text = placeholder');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as LineEdit');
lines.push('');
lines.push('func _mk_select(parent: Control, id: String, options: Array) -> OptionButton:');
lines.push('\tvar n := OptionButton.new()');
lines.push('\tfor o in options:');
lines.push('\t\tn.add_item(String(o))');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as OptionButton');
lines.push('');
lines.push('func _mk_feed(parent: Control, id: String) -> RichTextLabel:');
lines.push('\tvar n := RichTextLabel.new()');
lines.push('\tn.bbcode_enabled = true');
lines.push('\tn.custom_minimum_size = Vector2(540, 160)');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as RichTextLabel');
lines.push('');
lines.push('func _mk_group(parent: Control, id: String) -> VBoxContainer:');
lines.push('\tvar n := VBoxContainer.new()');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as VBoxContainer');
lines.push('');
lines.push('func _mk_grid(parent: Control, id: String, columns: int) -> GridContainer:');
lines.push('\tvar n := GridContainer.new()');
lines.push('\tn.columns = columns');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as GridContainer');
lines.push('');
lines.push('func _mk_tpl_button(parent: Control, key: String, text: String) -> Button:');
lines.push('\tvar n := Button.new()');
lines.push('\tn.text = text');
lines.push('\tn.set_meta("template_key", key)');
lines.push('\tparent.add_child(n)');
lines.push('\treturn n');
lines.push('');
lines.push('func _mk_rows(parent: Control, id: String, rows: Array) -> GridContainer:');
lines.push('\tvar n := GridContainer.new()');
lines.push('\tn.columns = 2');
lines.push('\tfor row: Array in rows:');
lines.push('\t\tvar l := Label.new()');
lines.push('\t\tl.text = String(row[0])');
lines.push('\t\tn.add_child(l)');
lines.push('\t\tvar v := Label.new()');
lines.push('\t\tv.text = String(row[1])');
lines.push('\t\tn.add_child(v)');
lines.push('\tparent.add_child(n)');
lines.push('\treturn _reg(id, n) as GridContainer');

fs.writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
console.log(`MEETING-UI POC EMIT ${path.relative(ROOT, OUT)}（${lines.length} 行 / ${spec.elements.length} 元素 / ${spec.templates.length} 模板）`);
