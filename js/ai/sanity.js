  function beliefEntropy(sus, skip) {
    const xs = [];
    let s = 0;
    for (const k in (sus || {})) {
      if (skip != null && String(skip) === k) continue;
      const v = sus[k] || 0;
      if (v <= 0) continue;
      xs.push(v); s += v;
    }
    if (xs.length < 2 || s <= 0) return 0;
    let h = 0;
    for (const v of xs) { const p = v / s; h -= p * Math.log(p); }
    return h;
  }

