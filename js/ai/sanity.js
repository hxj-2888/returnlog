  /* 风险纯函数：只做加总与夹取，状态由 game.js 传进来（便于单测与调参） */
  function disguiseRisk(p) {
    const R = DISGUISE.risk;
    let r = 0;
    if (p) {
      if (p.redHot) r += R.redHot;
      if (p.donePoint) r += R.donePoint;
      if (p.repeatSpot) r += R.repeatSpot;
      if (p.breakerLoss) r += R.breakerLoss;
      if (p.realCost) r += R.realCost;
      r += Math.min(R.idleCap, (p.idle || 0) * R.idleEyes);
      if ((p.audience || 0) >= 3) r += R.manyEyes;
      if (p.dark) r -= R.dark;
    }
    return clamp(r, 0, R.cap);
  }
  function disguiseScore(o) {
    const aud = o && o.audience ? o.audience : 0;
    if (aud <= 0) return 0;                       /* 没观众：一分不值 */
    const risk = clamp(o.risk || 0, 0, 1);
    /* valueMul（2026-11-03）：同样"被看见干一件正经事"，真修好一处故障比假装修更值钱。
       倍数由调用方从**既有数值**推出来（`CRED.gains[这件事] / CRED.gains.fakeWork`），
       这里不另立一档，所以它不是新的平衡旋钮，只是把"一次被目击的正经动作 ≈ 1 分"
       这个量纲落到不同动作上。缺省 1 = 与伪装同值。 */
    const mul = (o && o.valueMul > 0) ? o.valueMul : 1;
    const gain = DISGUISE.base * mul * Math.min(DISGUISE.maxAudience, aud) * (1 - risk);
    const cost = DISGUISE.timeCost * (o.duration || 0) + DISGUISE.riskCost * risk;
    return gain - cost;
  }

