  /* mem: mind.mem 数组；o: {subj, claimRoom, night, t0, t1, tRef}
     返回 {match, evidence, checked, age, room}
       match=true  → 口供成立，不可定罪
       checked=0   → 窗口内没有任何该对象的记录 → 无信息，闭嘴
       其余        → 可定罪，evidence 取最接近 tRef 的那条 */
  function checkAlibi(mem, o) {
    const out = { match: false, evidence: null, checked: 0, mismatched: 0, age: 0, room: null };
    if (!mem || !mem.length || !o || o.subj == null) return out;
    const t0 = o.t0, t1 = o.t1;
    if (t0 == null || t1 == null || t1 < t0) return out;
    const ref = o.tRef == null ? t1 : o.tRef;
    let best = null, bestD = Infinity;
    for (let k = mem.length - 1; k >= 0; k--) {
      const e = mem[k];
      if (!e || e.kind !== 'saw_agent') continue;
      if (e.subj !== o.subj) continue;
      if (o.night != null && e.night !== o.night) continue;
      /* 走廊/未知区域不算「在某个舱室」：走过一段走廊不能反驳口供，
         否则每个在走廊被瞥见的人都成了说谎者。 */
      if (e.room == null || e.room === 'corridor' || e.room === 'unknown') continue;
      if (e.t < t0 || e.t > t1) continue;
      out.checked++;
      if (o.claimRoom != null && e.room === o.claimRoom) { out.match = true; continue; }
      out.mismatched++;
      const d = Math.abs(e.t - ref);
      if (d < bestD) { bestD = d; best = e; }
    }
    if (!out.match && best) {
      out.evidence = best;
      out.room = best.room;
      out.age = Math.max(0, ref - best.t);
    }
    return out;
  }

