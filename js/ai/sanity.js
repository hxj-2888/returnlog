/* =============================================================
 * 新返航录 · 理智兜底 / 伪装收益 / 正向信任（Sanity）
 *
 * 职责分层：
 *   traits.js  回答「这个人**偏好**什么」—— 性格轴，是软的、可调的。
 *   本文件     回答「再偏好也**不能越过**哪条线」—— 理智，是硬的、不随性格走。
 *
 * 为什么要有这一层（2026-11-01 用户裁定）：
 *   性格化的第一版把"激进"直接写成了"敢在目击者面前动手"，结果是
 *   激进异形当着三个人的面出刀、当着人群拆设备 —— 这不是激进，是不合理。
 *   真人玩家再莽，也不会做**显而易见会自曝**的事；他的激进只体现在
 *   「同样安全的前提下，我更愿意赌一把」。所以性格必须装在理智的笼子里：
 *
 *     先过理智线（目击者数 / 暴露度 / 人群密度）→ 过了才轮到性格微调
 *
 * 全部数值都在下面四张表里，业务代码只查表，不写数字。
 * 调参只改这里；要恢复"性格全开"，把 traits.js 的 TRAIT_GAIN 调回 1 即可。
 * ============================================================= */
(function (global) {
  const clamp = (v, a, b) => (v < a ? a : (v > b ? b : v));

  /* ---------------- ⓪ 性格方差压缩 ----------------
     2026-11-01 用户裁定：「先暂时压制一下性格带来的方差」。
     0 = 全员行为完全一致；1 = 原始强度（旧行为）。
     traits.js 的 b() 统一乘这个系数，所以 SKTrait.C 里所有系数
     一次性收窄，不需要逐个改表。想恢复性格差异就调回 1，不要动系数表。 */
  const TRAIT_GAIN = 0.45;

  /* ---------------- ① 暴露度模型 ----------------
     不数人头，算"这一下有多显眼"。
     输入是**已经判定过视线**的目击者列表（由 game.js 用 losNow/aiCanSee 筛好），
     这里只做纯数学，方便单测与调参。 */

  /* 单个目击者的权重：贴脸 1.00 → 视野边缘 0.30；站桩做事的人注意力更集中（+0.12） */
  function witnessWeight(d, R, busy) {
    const t = clamp(d / Math.max(0.5, R), 0, 1);
    return Math.max(0, (1 - 0.70 * t) + (busy ? 0.12 : 0));
  }
  /* 逃逸成本：出刀后 killer.redT=3.0 三秒红身，离门/管道口越远越走不干净 */
  function escapeCost(dist) {
    return Math.max(0, 1.6 - dist / 3) * 0.25;
  }
  /* 汇总：2 个贴脸目击者 = 完全暴露（conceal 0） */
  function exposure(weights, esc) {
    let s = 0;
    for (let i = 0; i < weights.length; i++) s += weights[i];
    return clamp((s + (esc || 0)) / 2.0, 0, 1);
  }

  /* ---------------- ② 理智线（硬上限，性格不能突破） ----------------
     命名规则：*Cap   = 达到即放弃（计数）
               minConceal = 隐蔽度下限（0~1，越高越保守）
               crowdR/N  = 「在人群中」的判定半径与人数
     knife.bold 不是硬线，是**通过理智线之后**的冒险率区间：
     性格只能在这个窄区间里浮动（0.34~0.66），不再有 0.12~0.95 那种跨度。 */
  const KNIFE = {
    witnessCap: 3,        /* 非队友目击者 ≥3 → 一律放弃（用户原话：三个人能看到就不出手） */
    minConceal: 0.34,     /* 隐蔽度 < 0.34 → 换时机，不看性格 */
    crowdR: 9, crowdN: 3, /* 9 格内 ≥3 名非队友 = 在人群里，不出刀 */
    boldBase: 0.50, boldSpan: 0.16,
  };
  const SABOTAGE = {
    witnessCap: 1,        /* 有 1 个非队友在视线内就不破坏 */
    minConceal: 0.58,
    crowdR: 10, crowdN: 3,/* 10 格内 ≥3 人 = 在人群里（"人群"按 3 人起算，不是 2 人） */
  };
  const BREAKER = {
    witnessCap: 1,        /* 同上：有人看着不拉闸 */
    minConceal: 0.45,
    crowdR: 10, crowdN: 3,
  };

  /* ---------------- ③ 伪装收益表 ----------------
     异形"演一下"必须满足两个条件才值得：
       1) 真的有非队友在视线内（没有观众 = 收益 0，绝不莫名其妙演）；
       2) 收益分 > minScore。
     收益 = 观众数带来的信誉 × 不被看破的概率 − 站桩时间成本 − 风险成本。

     **量纲说明（改数值前先看这里）**：
       score 的单位是"一次被目击的正经动作 ≈ 1 分"。
       base=1.0 表示"1 个观众看到我干正经事"值 1 分；
       timeCost 按秒扣（5 秒 ≈ 0.1 分，站桩本来就不贵，异形这时候也没别的事干）；
       riskCost 是主刹车：risk=0 不扣，risk=0.5 扣 0.6 分。
       所以"1 个观众 + 低风险"≈ 0.85−0.1 = 0.75 分会演；
       "1 个观众 + 合闸（risk 0.45）"≈ 0.55−0.6 < 0 —— 得有两个以上观众才值。 */
  const DISGUISE = {
    audienceR: 8,
    base: 1.00,
    timeCost: 0.02,
    riskCost: 1.20,
    minScore: 0.25,
    maxAudience: 3,
    cooldown: 18,         /* 一次演完 18 秒内不再演：真人不会连着演，也防止刷分 */
    /* 假装修理的"就近"半径：故障平均只活 20 秒，8 格太苛刻（实测 0 次/局），
       放宽到 12 格才真的会走过去"帮忙"。 */
    fakeRepairR: 12,
  };
  function disguiseScore(o) {
    const aud = o && o.audience ? o.audience : 0;
    if (aud <= 0) return 0;                       /* 没观众：一分不值 */
    const risk = clamp(o.risk || 0, 0, 1);
    const gain = DISGUISE.base * Math.min(DISGUISE.maxAudience, aud) * (1 - risk);
    const cost = DISGUISE.timeCost * (o.duration || 0) + DISGUISE.riskCost * risk;
    return gain - cost;
  }

  /* ---------------- ④ 正向信任（cred） ----------------
     和 traits.js 的 trust（被辩护过的恩情）分开：
       trust = 「他帮过我」   → 情绪
       cred  = 「他干的是正经事」→ 能力与立场，异形伪装就是刷这一条
     来源全是**可被目击的正经行为**，每夜衰减，跨夜保留。
     作用：抬高指控门槛、投票回避、给证言加权 —— 也就是"洗白"。 */
  const CRED = {
    gains: {
      taskDone: 0.10,     /* 看见别人把任务做完 */
      fixDone: 0.16,      /* 看见别人修好破坏 */
      breakerOn: 0.14,    /* 看见别人合上电闸 */
      dragToMed: 0.10,    /* 看见别人把伤员拖向医疗间 */
      revive: 0.20,       /* 看见别人施救 */
      /* 异形伪装专用：目击者分不出"真做"和"假做"，所以也要给分，
         但略低于真做 —— 演出总有破绽（动作衔接、进度条走法）。 */
      fakeWork: 0.10,
    },
    decay: 0.92,          /* 每夜 ×0.92，慢衰减：洗白是长期投资 */
    cap: 1.2,
    /* 信誉到这条线以上、且手上没有确证 → 不再当众指控他。
       0.35 ≈ 被看见干了 3~4 件正经事。实测这个门槛在 300 局里**几乎不触发**
       （把值改成 9.99 关掉它，胜率一位小数都不变）—— 也就是说这条保护目前是
       "有机制、没手感"：真正起作用的洗白来自证言权重，不是它。
       保留 0.35 作为设计意图，等伪装频次上来后它会自然生效。 */
    accuseShieldAt: 0.35,
    voteShield: 0.55,     /* 投票回避概率 = min(0.85, cred × 0.55) */
    testimony: 0.60,      /* 证言权重里 cred 的系数 */
  };

  /* ---------------- ⑤ 追责（2026-11-01） ----------------
     投票结果公布后清算"带节奏"的人：
       · 被驱逐的**真是异形** → 投对的人信誉上升（别人更信他的判断）
       · 被驱逐的是**人类**   → 投错的人信誉下降，带头的人还被记一笔嫌疑
     第一个指控 / 第一个投的人权重最高（leadMul），跟票的按 voterMul 计。
     这条给了异形一个新风险：诬陷成功收益极大，但一旦被证伪，
     带头的人自己就变成下一个目标 —— 诬陷是要还的。 */
  const ACCOUNT = {
    correct: {cred: 0.10},                 /* 投对：+信誉 */
    wrong: {cred: -0.14, sus: 0.09},       /* 投错：-信誉，带头的 +嫌疑 */
    leadMul: 2.2,                          /* 带节奏的人效果翻倍 */
    voterMul: 0.55,                        /* 跟票的人按 55% 计 */
  };

  /* ---------------- ⑥ 诬陷（2026-11-01） ----------------
     异形没有目击也会编造具体证词（"我看见他出刀/钻管道"）。
     在听众眼里它和真目击者无法区分 —— 这是社交推理里最难拆的一手，
     所以概率不能高：chance 是"每场会议会诬陷的概率"。 */
  const FRAME = {
    chance: 0.55,          /* 有目标时，每场会议诬陷的概率 */
    knifeRatio: 0.55,      /* 诬陷"出刀"还是"钻管道" */
  };

  /* ---------------- ⑦ 讨论 → 关系（2026-11-01） ----------------
     用户要求："讨论要真的影响投票结果，甚至影响 AI 后续在实际场中的行为"。
     这里只做**最小一步**：讨论里共同指控过同一人 → 彼此 warm 上升；
     warm 高的人，空闲时会倾向走到一起（见 aiIdleRoam）。
     **幅度刻意压小**：warm 只在"任务全做完的空闲阶段"生效，且只有 45% 概率。 */
  const WARM = {
    coAccuse: 0.10,      /* 一起指控同一个人的两个人，彼此 +0.10 */
    defended: 0.12,      /* 被谁辩护过，对谁 +0.12 */
    decay: 0.85,         /* 每场会议 ×0.85 */
    minWarm: 0.22,       /* 低于这个值不算"聊得来" */
    range: 14,           /* 只找 14 格内的 */
    followChance: 0.45,  /* 空闲时往他那边走的概率（压小，避免影响平衡） */
  };

  /* ---------------- ⑧ 说服力（不是判断力） ----------------
     目击者的**判断**不可动摇（known 是硬约束，见 game.js）。
     但"他能不能说服别人"可以被削弱 —— 这是允许被影响的一侧。 */
  const TESTIFY = {
    dirtySus: 0.30,      /* 听众对他已有 ≥0.30 嫌疑 → 视为名声受损 */
    dirtyMul: 0.85,      /* 证言权重 ×0.85（只削 15%，幅度小） */
    corrobMul: 1.25,     /* 同一目标第二个独立指控者起 ×1.25（证据汇合） */
  };

  /* ---------------- ⑨ 领袖型玩家（2026-11-01） ----------------
     用户要求："四场或五场对局里会有一场，出现那种类似领袖型的玩家，
     可能是异形也可能是人类，会给每个玩家下达任务指令或者做总体安排。"
     设计要点：
       · **不预先判定阵营** —— 领袖只是"爱指挥"的人，可能是异形在带节奏；
       · 幅度压小：听指令的人对领袖 +0.06 warm，领袖点谁只 +0.02 嫌疑
         （远低于一次真实指控的 0.020~0.12，不会抢走证言的作用）；
       · 只有 soc 轴够高的人才可能当领袖，避免"最孤僻的人突然指挥全场"。 */
  const LEADER = {
    chance: 0.22,       /* 每局出现领袖的概率（≈ 1/4.5） */
    minSoc: 45,         /* soc 轴下限 */
    warmGain: 0.06,     /* 听众对领袖 +warm（很轻） */
    orderSus: 0.02,     /* 领袖点名的对象，听众 +0.02 嫌疑（很轻） */
    maxOrders: 2,       /* 每场会议最多下几条指令 */
  };

  /* 信誉 → 投票回避概率 */
  function credVoteShield(cred) {
    return clamp((cred || 0) * CRED.voteShield, 0, 0.85);
  }
  /* 信誉 → 证言权重倍率（1.0 ~ 1.6） */
  function credTestimony(cred) {
    return 1 + clamp((cred || 0) * CRED.testimony, 0, 0.6);
  }

  global.SKSanity = {
    TRAIT_GAIN,
    clamp, witnessWeight, escapeCost, exposure,
    KNIFE, SABOTAGE, BREAKER, DISGUISE, CRED, ACCOUNT, FRAME, WARM, TESTIFY, LEADER,
    disguiseScore, credVoteShield, credTestimony,
  };
})(window);
